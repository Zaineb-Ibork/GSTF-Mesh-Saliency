#!/usr/bin/env python3
"""
Generate LaTeX significance tables from significance_results.json.

Produces journal_paper/significance_table.tex (\\input-able), with one table per
data source: each variant vs the baseline, reporting the paired mean difference,
Holm-corrected Wilcoxon AND paired t-test p-values side by side, and Cliff's
delta. Uses booktabs, matching the paper's existing table style.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# Display label + feature dimension, in the paper's row order.
ROWS = [
    ("symf",          r"\;$+$ SymF",                 12),
    ("cr",            r"\;$+$ CR",                   18),
    ("pers",          r"\;$+$ Pers",                 12),
    ("symf+cr",       r"\;$+$ SymF $+$ CR",          21),
    ("symf+pers",     r"\;$+$ SymF $+$ Pers",        15),
    ("cr+pers",       r"\;$+$ CR $+$ Pers",          21),
    ("symf+cr+pers",  r"\;$+$ SymF $+$ CR $+$ Pers", 24),
    ("full+postproc", r"\;Full $+$ post-proc",       24),
]

# Which (PLCC source, AUC source) pair feeds each table, plus caption text.
TABLES = [
    dict(label="tab:sig-cv",
         plcc="schelling_perfold_PLCC", auc="schelling_perfold_AUC",
         title="Per-fold cross-validation (Schelling, $K{=}10$ per category, "
               "$n{=}200$ paired folds)",
         caption=(r"Statistical significance of each ablation variant against the "
                  r"$9$-D baseline under per-category $K{=}10$ cross-validation "
                  r"(Table~\ref{tab:cv}), tested on the $n{=}200$ paired per-fold "
                  r"scores. $\Delta$ is the mean improvement over the baseline; "
                  r"$p_{\mathrm{W}}$ and $p_{t}$ are the Holm-corrected Wilcoxon "
                  r"signed-rank and paired $t$-test $p$-values; $\delta$ is "
                  r"Cliff's delta. Bold marks a significant improvement ($p_{\mathrm{W}}<0.05$ and $\Delta>0$).")),
    dict(label="tab:sig-sota",
         plcc="sarma_permesh_PLCC", auc="sarma_permesh_AUC",
         title="Per-mesh (state-of-the-art protocol, $n{=}80$ paired meshes)",
         caption=(r"Statistical significance of each variant against the baseline "
                  r"on the $n{=}80$ per-mesh scores of the state-of-the-art "
                  r"comparison protocol (Table~\ref{tab:sota}). Columns as in "
                  r"Table~\ref{tab:sig-cv}.")),
]


def fmt_p(p):
    return r"$<$0.001" if p < 1e-3 else f"{p:.3f}"


def stars(p):
    return ("$^{***}$" if p < .001 else "$^{**}$" if p < .01
            else "$^{*}$" if p < .05 else "")


def row_lookup(rows):
    return {r["variant"]: r for r in rows}


def build_table(sig, spec):
    plcc = row_lookup(sig[spec["plcc"]])
    auc = row_lookup(sig[spec["auc"]])
    out = []
    out.append(r"\begin{table}[tb]")
    out.append(r"\caption{" + spec["caption"] + "}")
    out.append(r"\label{" + spec["label"] + "}")
    out.append(r"\centering")
    out.append(r"\footnotesize")
    out.append(r"\begin{tabular}{lc cccc cccc}")
    out.append(r"\toprule")
    out.append(r" & & \multicolumn{4}{c}{PLCC vs.\ baseline} "
               r"& \multicolumn{4}{c}{AUC vs.\ baseline}\\")
    out.append(r"\cmidrule(lr){3-6}\cmidrule(lr){7-10}")
    out.append(r"Model & Dim & $\Delta$ & $p_{\mathrm{W}}$ & $p_{t}$ & $\delta$"
               r" & $\Delta$ & $p_{\mathrm{W}}$ & $p_{t}$ & $\delta$\\")
    out.append(r"\midrule")
    for key, label, dim in ROWS:
        rp, ra = plcc[key], auc[key]

        def cell(r, field, bold=False):
            v = r[field]
            s = f"{v:+.3f}" if field == "mean_diff" else f"{v:+.2f}"
            return r"$\mathbf{" + s + "}$" if bold else f"${s}$"

        pw_p, pt_p = rp["wilcoxon_p_holm"], rp["ttest_p_holm"]
        aw_p, at_p = ra["wilcoxon_p_holm"], ra["ttest_p_holm"]
        # Bold marks a significant *improvement* (p<0.05 AND positive delta).
        bold_p_plcc = pw_p < 0.05 and rp["mean_diff"] > 0
        bold_p_auc = aw_p < 0.05 and ra["mean_diff"] > 0
        out.append(
            f"{label:<30} & {dim:>2} & "
            f"{cell(rp,'mean_diff', bold_p_plcc)} & "
            f"{fmt_p(pw_p)}{stars(pw_p)} & {fmt_p(pt_p)} & {cell(rp,'cliffs_delta')} & "
            f"{cell(ra,'mean_diff', bold_p_auc)} & "
            f"{fmt_p(aw_p)}{stars(aw_p)} & {fmt_p(at_p)} & {cell(ra,'cliffs_delta')}"
            r"\\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    return "\n".join(out)


def main():
    sig = json.load(open(os.path.join(HERE, "significance_results.json")))
    blocks = [r"% Auto-generated by make_significance_table.py -- do not edit by hand.",
              r"% Source: significance_results.json (compute_significance.py)."]
    for spec in TABLES:
        if spec["plcc"] in sig and spec["auc"] in sig:
            blocks.append(build_table(sig, spec))
            blocks.append("")
    tex = "\n".join(blocks) + "\n"
    dst = os.path.join(HERE, "journal_paper", "significance_table.tex")
    with open(dst, "w") as f:
        f.write(tex)
    print(f"Wrote {dst}\n")
    print(tex)


if __name__ == "__main__":
    main()
